/** كلماتٌ لا تحمل مقصداً — تُطرح قبل الموازنة */
const STOP = new Set([
  "اريد", "ابغى", "ابي", "بدي", "عايز", "عاوز", "ودي", "احتاج", "كيف", "شلون", "وش",
  "ما", "هو", "هي", "من", "في", "على", "الى", "عن", "ان", "هذا", "هذه", "لو", "سمحت",
  "ممكن", "please", "want", "need", "how", "to", "i", "my", "the", "a",
]);

const tokens = (s: string) =>
  normalizeAr(s).split(/[\s،,.؟?!]+/).filter((w) => w.length > 1 && !STOP.has(w));

export type IntentMatch = { intent: Intent; score: number };

/**
 * يوازن مقصدَ المستخدم بعباراتِ النيّات.
 * المطابقةُ على مستوى الكلمات لا الحرف، فـ«ابغى احسب ربح المنتج» تصل إلى التسعير.
 */
export function matchIntents(query: string, limit = 3): IntentMatch[] {
  const qTokens = tokens(query);
  if (qTokens.length === 0) return [];
  const qNorm = normalizeAr(query);

  const out: IntentMatch[] = [];
  for (const intent of INTENTS) {
    let best = 0;
    for (const phrase of intent.phrases) {
      const pNorm = normalizeAr(phrase);
      const pTokens = tokens(phrase);
      if (pTokens.length === 0) continue;

      // عبارةٌ كاملةٌ داخل السؤال — أقوى إشارة
      if (qNorm.includes(pNorm)) { best = Math.max(best, 100 + pNorm.length); continue; }

      const shared = pTokens.filter((t) => qTokens.some((q) => q === t || q.includes(t) || t.includes(q)));
      if (shared.length === 0) continue;
      // نسبةُ ما تحقّق من العبارة، لا عددُ الكلمات وحدَه
      best = Math.max(best, (shared.length / pTokens.length) * 60 + shared.length * 8);
    }
    if (best > 0) out.push({ intent, score: best });
  }
  return out.sort((a, b) => b.score - a.score).slice(0, limit);
}

